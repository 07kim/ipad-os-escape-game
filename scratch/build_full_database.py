# 共通HTMLビルダー（ニュース記事として自然な見出し・コラム構成）
def build_article_html(title, chapters, dialogue_title, dialogue_items, report_title, report_body, reaction_items, timeline_rows, closing_text, enrichments=None, sec_enrichments=None):
    html = f"<h3 class='news-main-title'>{title}</h3>\n"
    
    # 本文各セクション（「第1章」等の章立てを完全排除し、自然なニュース小見出しへ変換）
    for idx, (ch_title, paras) in enumerate(chapters):
        # 「【第X章：...】」などの小説・論文風の章立てを除去し、自然な小見出しに整形
        clean_heading = re.sub(r'【第\d+章[：:]?\s*', '', ch_title).replace('】', '')
        clean_heading = re.sub(r'^第\d+章[：:]?\s*', '', clean_heading).strip()
        
        html += f"<h4 class='news-sub-title'>■ {clean_heading}</h4>\n"
        for p in paras:
            html += f"<p>{p}</p>\n"
            
        # 各セクション末尾の現場取材メモ・コラム
        if enrichments and idx < len(enrichments):
            html += f"<p style='background:#f8fafc; padding:12px 18px; border-left:4px solid #0284c7; border-radius:6px; margin:16px 0; font-size:13.5px; line-height:1.75;'><strong>【現地取材ノート】</strong>{enrichments[idx]}</p>\n"
        if sec_enrichments:
            for s_idx, sec_text in enumerate(sec_enrichments):
                if s_idx % len(chapters) == idx:
                    html += f"<p style='background:#f0fdf4; padding:12px 18px; border-left:4px solid #16a34a; border-radius:6px; margin:16px 0; font-size:13.5px; line-height:1.75;'><strong>【背景分析・関連資料】</strong>{sec_text}</p>\n"
            
    # インタビュー・対談セクション
    if dialogue_items:
        clean_dialogue_title = re.sub(r'【特別対談・ロングインタビュー】', '', dialogue_title).strip()
        items_html = "<br>\n".join([f"・「{d}」" for d in dialogue_items])
        html += f"""<h4 class='news-sub-title'>■ 【特別インタビュー】{clean_dialogue_title}</h4>
<div style="background:#f8fafc; border:1.5px solid #cbd5e1; border-radius:12px; padding:20px 24px; margin:22px 0; line-height:1.9;">
  {items_html}
</div>\n"""

    # 調査レポートセクション
    if report_body:
        clean_report_title = re.sub(r'【深層追跡レポート】', '', report_title).strip()
        html += f"""<h4 class='news-sub-title'>■ 【調査レポート】{clean_report_title}</h4>
<p>{report_body}</p>\n"""

    # 街頭の声・世論
    if reaction_items:
        react_html = "<br>\n".join([f"・「{r}」" for r in reaction_items])
        html += f"""<h4 class='news-sub-title'>■ 【街頭の声・SNSの反応】</h4>
<div style="background:#fffbeb; border:1.5px solid #fde68a; border-radius:12px; padding:18px 22px; margin:20px 0; line-height:1.8;">
  <strong style="color:#b45309; font-size:15px;">【市民の声・世論の反響】</strong><br>
  {react_html}
</div>\n"""

    # 関連年表・経緯
    if timeline_rows:
        rows_html = "".join([f"<tr><td style='font-weight:bold; width:28%;'>{y}</td><td>{d}</td></tr>" for y, d in timeline_rows])
        html += f"""<h4 class='news-sub-title'>■ 【これまでの経緯・関連年表】</h4>
<table style="width:100%; margin:20px 0;">
  <thead>
    <tr><th>年代 / 項目</th><th>詳細内容・出来事</th></tr>
  </thead>
  <tbody>
    {rows_html}
  </tbody>
</table>\n"""

    # 記者コラム・結び
    if closing_text:
        html += f"""<h4 class='news-sub-title'>■ 【取材を終えて】</h4>
<p>{closing_text}</p>\n"""

    return html

