def build_article_html(title, chapters, dialogue_title, dialogue_items, report_title, report_body, reaction_items, timeline_rows, closing_text):
    html = f"<h3>{title}</h3>\n"
    
    # 本文各章
    for ch_title, paras in chapters:
        html += f"<h4>■ {ch_title}</h4>\n"
        for p in paras:
            html += f"<p>{p}</p>\n"
            
    # インタビュー対談
    if dialogue_items:
        items_html = "<br>\n".join([f"・「{d}」" for d in dialogue_items])
        html += f"""<h4>■ 【特別対談・ロングインタビュー】{dialogue_title}</h4>
<div style="background:#f8fafc; border:1.5px solid #cbd5e1; border-radius:12px; padding:20px 24px; margin:22px 0; line-height:1.9;">
  {items_html}
</div>\n"""

    # 特捜データ・深層レポート
    if report_body:
        html += f"""<h4>■ 【深層追跡レポート】{report_title}</h4>
<p>{report_body}</p>\n"""

    # 市民の声・世論
    if reaction_items:
        react_html = "<br>\n".join([f"・「{r}」" for r in reaction_items])
        html += f"""<h4>■ 【世論の反響・市民の声】</h4>
<div style="background:#fffbeb; border:1.5px solid #fde68a; border-radius:12px; padding:18px 22px; margin:20px 0; line-height:1.8;">
  <strong style="color:#b45309; font-size:15px;">【街頭インタビュー＆SNSトレンド】</strong><br>
  {react_html}
</div>\n"""

    # 歴史年表・推移表
    if timeline_rows:
        rows_html = "".join([f"<tr><td style='font-weight:bold; width:28%;'>{y}</td><td>{d}</td></tr>" for y, d in timeline_rows])
        html += f"""<h4>■ 【歴史年表・事象の時系列推移】</h4>
<table style="width:100%; margin:20px 0;">
  <thead>
    <tr><th>年代 / 項目</th><th>詳細内容・出来事</th></tr>
  </thead>
  <tbody>
    {rows_html}
  </tbody>
</table>\n"""

    # 記者総括
    if closing_text:
        html += f"""<h4>■ 【取材記者総括・編集後記】</h4>
<p>{closing_text}</p>\n"""

    return html

